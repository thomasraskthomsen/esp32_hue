//! Renders icons from Material Design Icons into anti-aliased bitmaps for the
//! display and writes them to crates/tdongle/src/fonts.rs. Run it from
//! tools/fontgen (it isn't in the firmware workspace) after changing the
//! icons or sizes below:
//!
//! ```text
//! cargo +stable run --target x86_64-pc-windows-msvc
//! ```
//!
//! (The target overrides the firmware's `.cargo/config.toml`.)
//!
//! Each icon is stored with 4 bits of coverage per pixel, two pixels to a
//! byte, high nibble first; each row starts on a byte.

use ab_glyph::{Font, FontRef, PxScale, ScaleFont, point};

/// Name in the firmware, code point in Material Design Icons, height in pixels
/// of the icon's em square (the icon itself is a little smaller).
const ICONS: &[(&str, u32, f32)] = &[("CLOCK_OUTLINE", 0xF0150, 22.0)];

fn main() {
    let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../..");
    let ttf = std::fs::read(format!("{root}/tools/fontgen/fonts/MaterialDesignIcons.ttf")).unwrap();
    let font = FontRef::try_from_slice(&ttf).unwrap();
    let mut out = String::from(
        "//! Icons from Material Design Icons (Apache 2.0, see\n\
         //! tools/fontgen/fonts/MaterialDesignIcons-LICENSE.txt), generated by\n\
         //! tools/fontgen. Don't edit.\n\n\
         use crate::aafont::Icon;\n",
    );
    for &(name, code_point, size) in ICONS {
        render(&mut out, name, &font, char::from_u32(code_point).unwrap(), size);
    }
    std::fs::write(format!("{root}/crates/tdongle/src/fonts.rs"), out).unwrap();
}

fn render(out: &mut String, name: &str, font: &FontRef, c: char, size: f32) {
    let id = font.glyph_id(c);
    assert!(id.0 != 0, "{name}: the font has no glyph for U+{:X}", c as u32);
    let scaled = font.as_scaled(PxScale::from(size));
    let outline = scaled
        .outline_glyph(id.with_scale_and_position(size, point(0.0, 0.0)))
        .unwrap_or_else(|| panic!("{name}: the glyph has no outline"));
    let bounds = outline.px_bounds();
    let (width, height) = (bounds.width() as usize, bounds.height() as usize);
    let mut coverage = vec![0u8; width * height];
    outline.draw(|x, y, c| {
        let (x, y) = (x as usize, y as usize);
        if x < width && y < height {
            coverage[y * width + x] = (c.clamp(0.0, 1.0) * 15.0).round() as u8;
        }
    });
    // A look at the result, to check that it is the icon wanted.
    for row in coverage.chunks(width) {
        let art: String = row.iter().map(|&c| [' ', '.', ':', '#'][usize::from(c) * 3 / 15]).collect();
        eprintln!("    |{art}|");
    }
    let mut data: Vec<u8> = Vec::new();
    for row in coverage.chunks(width) {
        for pair in row.chunks(2) {
            data.push(pair[0] << 4 | pair.get(1).copied().unwrap_or(0));
        }
    }
    eprintln!("{name}: U+{:X} at {size}px, {width}x{height} pixels, {} bytes", c as u32, data.len());
    out.push_str(&format!(
        "\npub static {name}: Icon = Icon {{\n    width: {width},\n    height: {height},\n    data: &{data:?},\n}};\n"
    ));
}
